"""
Runs the demo signal sanity check and the Monte Carlo POP simulation for
all seven strategies, and regenerates results/summary.md.

Usage: python results/run_all.py (from anywhere, paths resolve relative
to this file).
"""

import importlib.util
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STRATEGIES_DIR = os.path.join(ROOT, "strategies")

STRATEGY_FOLDERS = [
    "01_ema_crossover_scalper",
    "02_vwap_trend_reversion",
    "03_orb_premium_breakout",
    "04_supertrend_adx_trend",
    "05_oi_pcr_filter",
    "06_intraday_momentum",
    "07_vol_squeeze_breakout",
]


def load_strategy_module(folder):
    path = os.path.join(STRATEGIES_DIR, folder, "strategy.py")
    spec = importlib.util.spec_from_file_location(f"strategy_{folder}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    rows = []
    for folder in STRATEGY_FOLDERS:
        print(f"\n=== {folder} ===")
        module = load_strategy_module(folder)
        try:
            module.demo()
        except Exception as exc:
            print(f"[demo failed: {exc}]")

        result = module.pop_simulation()
        if "pop" in result:
            r = result
            print(f"win_rate={r['win_rate_input']:.0%} POP={r['pop']:.0%} "
                  f"expectancy/trade=Rs {r['expectancy_per_trade_rupees']:.1f} "
                  f"p05_drawdown=Rs {r['p05_max_drawdown_rupees']:.0f}")
        else:
            for name, r in result.items():
                print(f"[{name}] win_rate={r['win_rate_input']:.0%} POP={r['pop']:.0%} "
                      f"expectancy/trade=Rs {r['expectancy_per_trade_rupees']:.1f}")
        rows.append((folder, module.CONFIG, result))

    write_summary(rows)


def write_summary(rows):
    lines = [
        "# Strategy comparison summary",
        "",
        "Generated by `results/run_all.py`. POP and expectancy come from the cost aware "
        "Monte Carlo simulator (`strategies/common/monte_carlo.py`), seeded with win rate "
        "and reward to risk assumptions sourced from the research report, not from live "
        "trading or a real historical backtest (no licensed NSE tick/options data feed was "
        "reachable from this environment). See `results/METHODOLOGY.md` for what these "
        "numbers are and are not.",
        "",
        "| Strategy | Instrument | Lots | Assumed win rate | POP (250 trades) | Expectancy/trade | P05 drawdown |",
        "|---|---|---|---|---|---|---|",
    ]
    for folder, config, result in rows:
        if "pop" in result:
            r = result
            lines.append(
                f"| {folder} | {config['instrument']} | {config['num_lots']} | "
                f"{r['win_rate_input']:.0%} | {r['pop']:.0%} | "
                f"Rs {r['expectancy_per_trade_rupees']:.1f} | Rs {r['p05_max_drawdown_rupees']:.0f} |"
            )
        else:
            for name, r in result.items():
                lines.append(
                    f"| {folder} ({name}) | {config['instrument']} | {config['num_lots']} | "
                    f"{r['win_rate_input']:.0%} | {r['pop']:.0%} | "
                    f"Rs {r['expectancy_per_trade_rupees']:.1f} | n/a |"
                )

    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "summary.md")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    main()
