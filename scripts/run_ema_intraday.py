"""
Intraday EMA crossover experiments on NIFTY and BANKNIFTY 1-minute data
(Jan 2011 to Feb 2023), always flat by 15:15, no new entries from 15:00.

D1. timeframe x EMA pair grid, gross and after costs
D2. filters on the most popular setup (9/21 on 5-minute bars)
D3. the original algo branch idea: 9/21 on 1-minute bars, fixed point
    target and stop, 5 bar time stop
D4. in-sample (2011-2017) selection, out-of-sample (2018-Feb 2023) test
D5. where the P&L comes from: by hour of entry

Prices are the spot index. Futures track spot closely intraday, so spot
P&L stands in for futures P&L; costs are the futures cost stack.

Usage: python scripts/run_ema_intraday.py
"""

import os
import sys
import time

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from ema_lab import costs, data, engine, indicators as ind, metrics, stats
from ema_lab import strategies as st
from ema_lab.report_utils import INK, SERIES, diverging_cmap, fig_path, markdown, save_table, setup_matplotlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TIMEFRAMES = [1, 3, 5, 15, 30]
PAIRS = [(5, 13), (9, 21), (12, 26), (20, 50)]
COST_LEVELS = {"gross": 0.0, "2024 costs": costs.per_side(costs.NSE_FUTURES_2024),
               "2026 costs": costs.per_side(costs.NSE_FUTURES_2026)}
SPLIT = pd.Timestamp("2017-12-31")


def session(sig, df, **kw):
    return st.with_session(sig, df.index, **kw)


def run_one(df, sig, cost):
    r = engine.run(df, sig, cost)
    s = metrics.summarize(r)
    s["expectancy_bps"] = s["expectancy"] * 1e4
    return s, r


def main():
    t0 = time.time()
    plt = setup_matplotlib()
    md = ["# Intraday EMA crossover results\n",
          "Generated by `scripts/run_ema_intraday.py`. NIFTY and BANKNIFTY spot 1-minute bars, Jan 2011 "
          "to Feb 2023, resampled to each timeframe inside the session. Long and short, fills at the "
          "next bar's open, no new entries from 15:00, flat at 15:15. Costs per side: 2024 stack "
          f"{costs.NSE_FUTURES_2024} bps, 2026 stack {costs.NSE_FUTURES_2026} bps (STT 0.05%).\n"]

    minute = {s: data.load_intraday(s) for s in ["NIFTY", "BANKNIFTY"]}
    bars = {(s, tf): data.resample_session(m, tf) for s, m in minute.items() for tf in TIMEFRAMES}
    print(f"loaded {time.time() - t0:.0f}s")

    # D1 grid
    rows = []
    for (sym, tf), df in bars.items():
        for fast, slow in PAIRS:
            sig = session(st.ema_cross(df, fast, slow, "long_short"), df)
            for label, cost in COST_LEVELS.items():
                s, r = run_one(df, sig, cost)
                s.update({"market": sym, "timeframe": f"{tf}m", "tf": tf, "rule": f"EMA {fast}/{slow}",
                          "costs": label})
                if label == "gross":
                    gross_exp = s["expectancy"]
                s["breakeven_bps_per_side"] = gross_exp * 1e4 / 2
                rows.append(s)
    g = pd.DataFrame(rows)
    save_table(g, "D1_intraday_grid")
    print(f"D1 {time.time() - t0:.0f}s")

    md.append("## D1. Timeframe x EMA pair, long/short, gross and net\n")
    md.append("`breakeven_bps_per_side` is the cost per fill at which the average trade nets zero. "
              f"Compare it with {costs.NSE_FUTURES_2026} bps (2026) and {costs.NSE_FUTURES_2024} bps (2024).\n")
    for sym in minute:
        sub = g[(g.market == sym) & (g.costs.isin(["gross", "2026 costs"]))].copy()
        piv = sub.pivot_table(index=["timeframe", "tf", "rule"], columns="costs",
                              values=["trades_per_year", "win_rate", "expectancy_bps", "profit_factor", "cagr"],
                              aggfunc="first")
        out = pd.DataFrame({
            "timeframe": [i[0] for i in piv.index], "rule": [i[2] for i in piv.index],
            "trades_per_year": piv[("trades_per_year", "gross")].values,
            "gross_win_rate": piv[("win_rate", "gross")].values,
            "gross_expectancy_bps": piv[("expectancy_bps", "gross")].values,
            "gross_pf": piv[("profit_factor", "gross")].values,
            "net_win_rate": piv[("win_rate", "2026 costs")].values,
            "net_expectancy_bps": piv[("expectancy_bps", "2026 costs")].values,
            "net_pf": piv[("profit_factor", "2026 costs")].values,
            "net_cagr": piv[("cagr", "2026 costs")].values,
            "tf": [i[1] for i in piv.index],
        }).sort_values(["tf", "rule"])
        be = g[(g.market == sym) & (g.costs == "gross")].set_index(["timeframe", "rule"])["breakeven_bps_per_side"]
        out["breakeven_bps_per_side"] = [be[(a, b)] for a, b in zip(out.timeframe, out.rule)]
        md.append(f"**{sym}**\n")
        md.append(markdown(out, ["timeframe", "rule", "trades_per_year", "gross_win_rate", "gross_expectancy_bps",
                                 "gross_pf", "breakeven_bps_per_side", "net_win_rate", "net_expectancy_bps",
                                 "net_pf", "net_cagr"]))
        md.append("")

    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    for ax, sym in zip(axes, minute):
        sub = g[(g.market == sym) & (g.costs == "gross")]
        piv = sub.pivot(index="rule", columns="tf", values="expectancy_bps").reindex([f"EMA {a}/{b}" for a, b in PAIRS])
        lim = max(abs(piv.values).max(), 1)
        im = ax.imshow(piv.values, cmap=diverging_cmap(), vmin=-lim, vmax=lim, aspect="auto")
        ax.set_xticks(range(len(piv.columns)), [f"{c}m" for c in piv.columns])
        ax.set_yticks(range(len(piv.index)), piv.index)
        ax.grid(False)
        for (a, b), v in np.ndenumerate(piv.values):
            ax.text(b, a, f"{v:.1f}", ha="center", va="center", fontsize=8, color=INK["primary"])
        ax.set_title(f"{sym}: gross bps per trade, before any cost")
        fig.colorbar(im, ax=ax, shrink=0.8)
    fig.suptitle(f"Intraday EMA crossovers earn a few bps per trade gross; a round trip costs {2 * costs.NSE_FUTURES_2026:.0f} bps in 2026",
                 fontweight="bold")
    fig.tight_layout()
    fig.savefig(fig_path("D1_intraday_gross_expectancy"))
    plt.close(fig)
    md.append("![intraday gross](figures/D1_intraday_gross_expectancy.png)\n")

    # D2 filters on 9/21 5m
    md.append("## D2. Filters on 9/21 EMA, 5-minute bars\n")
    rows = []
    for sym in minute:
        df = bars[(sym, 5)]
        c = df["close"]
        adx14 = ind.adx(df, 14)[0].to_numpy()
        ema200 = ind.ema(c, 200).to_numpy()
        daily = data.daily_from_intraday(minute[sym])
        d_ema = ind.ema(daily["close"], 20)
        # yesterday's daily trend, known before today's open
        d_trend = np.sign(d_ema.diff()).shift(1).reindex(df.index.normalize()).to_numpy()
        variants = {
            "base 9/21": {},
            "+ ADX(14) > 25": {"adx": 25},
            "+ windows 09:30-11:30, 13:30-14:45": {"windows": True},
            "+ 5m close vs EMA 200": {"ema200": True},
            "+ daily EMA 20 slope (prior day)": {"daily": True},
            "all filters": {"adx": 25, "windows": True, "ema200": True, "daily": True},
        }
        base = st.ema_cross_filtered(df, 9, 21, "long_short")
        for name, v in variants.items():
            sig = dict(base)
            ok_l = np.ones(len(df), bool)
            ok_s = np.ones(len(df), bool)
            if "adx" in v:
                ok_l &= adx14 > v["adx"]
                ok_s &= adx14 > v["adx"]
            if v.get("ema200"):
                ok_l &= c.to_numpy() > ema200
                ok_s &= c.to_numpy() < ema200
            if v.get("daily"):
                ok_l &= d_trend > 0
                ok_s &= d_trend < 0
            if v.get("windows"):
                t = df.index.hour * 100 + df.index.minute
                w = ((t >= 930) & (t <= 1130)) | ((t >= 1330) & (t <= 1445))
                ok_l &= w
                ok_s &= w
            sig["long_entry"] = base["long_entry"] & ok_l
            sig["short_entry"] = base["short_entry"] & ok_s
            sig = session(sig, df)
            for label in ["gross", "2026 costs"]:
                s, r = run_one(df, sig, COST_LEVELS[label])
                s.update({"market": sym, "filter": name, "costs": label})
                if label == "2026 costs":
                    rt = stats.random_entry_test(df, r.trades, COST_LEVELS[label], n_sims=300, same_day=True)
                    s["p_random"] = rt["p_value"]
                rows.append(s)
    f2 = pd.DataFrame(rows)
    save_table(f2, "D2_intraday_filters")
    for sym in minute:
        sub = f2[f2.market == sym]
        gross = sub[sub.costs == "gross"].set_index("filter")
        net = sub[sub.costs == "2026 costs"].set_index("filter")
        out = pd.DataFrame({
            "filter": gross.index, "trades_per_year": gross.trades_per_year.values,
            "gross_win_rate": gross.win_rate.values, "gross_expectancy_bps": gross.expectancy_bps.values,
            "net_win_rate": net.win_rate.values, "net_expectancy_bps": net.expectancy_bps.values,
            "net_pf": net.profit_factor.values, "net_cagr": net.cagr.values, "net_max_dd": net.max_dd.values,
            "p_random": net.p_random.values,
        })
        md.append(f"**{sym}**\n")
        md.append(markdown(out))
        md.append("")
    print(f"D2 {time.time() - t0:.0f}s")

    # D3 original fixed point scalper on 1m
    md.append("## D3. The original idea: 9/21 EMA on 1-minute bars, fixed target and stop\n")
    md.append("From the algo branch: enter on the cross, exit at +8 / -5 index points (about +4 / -2.5 "
              "option premium points at 0.5 delta) or after 5 bars. Results in index points per trade. "
              "Option costs per round trip were about 2 premium points (about 4 index points of "
              "equivalent move at 0.5 delta) per the algo branch cost model; futures costs are "
              f"{2 * costs.NSE_FUTURES_2026:.0f} bps of notional.\n")
    rows = []
    for sym in minute:
        df = bars[(sym, 1)]
        for tgt, stp in [(8, 5), (8, 8), (15, 10), (25, 15)]:
            sig = session(st.fixed_point_scalper(df, 9, 21, tgt, stp, 5), df)
            r = engine.run(df, sig, 0.0)
            tr = r.trades
            pts = tr.direction * (tr.exit_price - tr.entry_price)
            fut_cost_pts = 2 * costs.NSE_FUTURES_2026 / 1e4 * tr.entry_price
            for label, net in [("gross", pts), ("option-like 4 pts", pts - 4.0), ("futures 2026", pts - fut_cost_pts)]:
                wins = net[net > 0]
                losses = net[net <= 0]
                rows.append({"market": sym, "target/stop pts": f"{tgt}/{stp}", "costs": label,
                             "trades": len(net), "trades_per_year": len(net) / 12.15,
                             "win_rate": (net > 0).mean(), "avg_win_pts": wins.mean(), "avg_loss_pts": losses.mean(),
                             "expectancy_pts": net.mean(), "profit_factor": wins.sum() / -losses.sum(),
                             "total_pts_per_year": net.sum() / 12.15,
                             "exit_target_pct": (tr.exit_reason == "target").mean(),
                             "exit_stop_pct": (tr.exit_reason == "stop").mean()})
    f3 = pd.DataFrame(rows)
    save_table(f3, "D3_fixed_point_scalper")
    md.append(markdown(f3))
    md.append("")
    print(f"D3 {time.time() - t0:.0f}s")

    # D4 in-sample / out-of-sample on the D1 grid, 2026 costs
    md.append("## D4. In-sample 2011-2017 selection, out-of-sample 2018-Feb 2023 (2026 costs)\n")
    rows = []
    for sym in minute:
        res = []
        for tf in TIMEFRAMES:
            df = bars[(sym, tf)]
            for fast, slow in PAIRS:
                sig = session(st.ema_cross(df, fast, slow, "long_short"), df)
                for label in ["gross", "2026 costs"]:
                    r = engine.run(df, sig, COST_LEVELS[label])
                    ins = metrics.equity_stats(r.returns.loc[:SPLIT])
                    oos = metrics.equity_stats(r.returns.loc[SPLIT + pd.Timedelta(days=1):])
                    res.append({"tf": tf, "rule": f"{tf}m EMA {fast}/{slow}", "costs": label,
                                "is_sharpe": ins["sharpe"], "oos_sharpe": oos["sharpe"],
                                "is_cagr": ins["cagr"], "oos_cagr": oos["cagr"]})
        res = pd.DataFrame(res)
        for label in ["gross", "2026 costs"]:
            sub = res[res.costs == label]
            best = sub.loc[sub.is_sharpe.idxmax()]
            rows.append({"market": sym, "costs": label, "best_in_sample": best.rule,
                         "is_sharpe": best.is_sharpe, "is_cagr": best.is_cagr,
                         "oos_sharpe": best.oos_sharpe, "oos_cagr": best.oos_cagr,
                         "configs_with_oos_sharpe_above_0_pct": (sub.oos_sharpe > 0).mean(),
                         "is_oos_rank_corr": sub[["is_sharpe", "oos_sharpe"]].corr(method="spearman").iloc[0, 1]})
    f4 = pd.DataFrame(rows)
    save_table(f4, "D4_intraday_is_oos")
    md.append(markdown(f4))
    md.append("")
    print(f"D4 {time.time() - t0:.0f}s")

    # D5 P&L by entry hour, 9/21 on 5m, gross
    md.append("## D5. Gross P&L by hour of entry (9/21, 5-minute bars)\n")
    rows = []
    for sym in minute:
        df = bars[(sym, 5)]
        r = engine.run(df, session(st.ema_cross(df, 9, 21, "long_short"), df), 0.0)
        tr = r.trades.copy()
        tr["hour"] = tr.entry_time.dt.hour
        h = tr.groupby("hour").agg(trades=("ret", "size"), win_rate=("ret", lambda x: (x > 0).mean()),
                                   mean_bps=("ret", lambda x: x.mean() * 1e4)).reset_index()
        h.insert(0, "market", sym)
        rows.append(h)
    f5 = pd.concat(rows)
    save_table(f5, "D5_intraday_by_hour")
    md.append(markdown(f5))
    md.append("")

    # D6 spot vs near-month futures, the instrument you would actually trade
    md.append("## D6. Spot index vs near-month futures (the tradable instrument)\n")
    md.append("Index spot values are computed from 50 constituent prices, and stale constituents can "
              "add short-horizon momentum that no one can trade. Re-running the main setups on the "
              "continuous near-month futures (NIFTY_F1, BANKNIFTY_F1; intraday only, so contract rolls "
              "between sessions do not matter):\n")
    rows = []
    for spot, fut in [("NIFTY", "NIFTY_F1"), ("BANKNIFTY", "BANKNIFTY_F1")]:
        fut_min = data.load_intraday(fut)
        for sym, m in [(spot, minute[spot]), (fut, fut_min)]:
            r1 = np.log(m["close"]).diff()
            same = m.index.normalize() == pd.Series(m.index.normalize()).shift(1).to_numpy()
            ac1 = r1[same].autocorr(1)
            for tf in [1, 5, 15]:
                df = data.resample_session(m, tf)
                for fast, slow in [(9, 21), (20, 50)]:
                    sig = session(st.ema_cross(df, fast, slow, "long_short"), df)
                    g_, _ = run_one(df, sig, 0.0)
                    n_, _ = run_one(df, sig, COST_LEVELS["2026 costs"])
                    rows.append({"series": sym, "timeframe": f"{tf}m", "rule": f"EMA {fast}/{slow}",
                                 "trades_per_year": g_["trades_per_year"], "gross_win_rate": g_["win_rate"],
                                 "gross_expectancy_bps": g_["expectancy_bps"], "gross_sharpe": g_["sharpe"],
                                 "net_expectancy_bps": n_["expectancy_bps"], "net_cagr": n_["cagr"],
                                 "lag1_autocorr_1m": ac1})
    f6 = pd.DataFrame(rows)
    save_table(f6, "D6_spot_vs_futures")
    md.append(markdown(f6))
    md.append("\nOne-minute return autocorrelation is near zero for both, so staleness is not "
              "manufacturing the signal, but the gross edge on futures is generally smaller than on spot.\n")
    print(f"D6 {time.time() - t0:.0f}s")

    # equity curves, 9/21 5m gross vs net
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8), sharey=False)
    for ax, sym in zip(axes, minute):
        df = bars[(sym, 5)]
        sig = session(st.ema_cross(df, 9, 21, "long_short"), df)
        for k, label in enumerate(COST_LEVELS):
            r = engine.run(df, sig, COST_LEVELS[label])
            eq = (1 + metrics.daily_returns(r.returns)).cumprod()
            ax.plot(eq.index, eq.values, color=SERIES[k], label=label)
        ax.set_yscale("log")
        ax.set_title(f"{sym} 9/21 EMA, 5-minute, long/short intraday")
        ax.set_ylabel("growth of 1 (log scale)")
        ax.legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(fig_path("D_intraday_equity"))
    plt.close(fig)
    md.append("![intraday equity](figures/D_intraday_equity.png)\n")

    with open(os.path.join(ROOT, "results", "ema_intraday.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print(f"done {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
